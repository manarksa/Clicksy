export const messages = { en, ar }
export type Lang = keyof typeof messages
export type Messages = (typeof messages)['en']
export type AuthErrorCode = keyof Messages['errors']

export function formatDate(iso: string, lang: Lang) {
  if (!iso) return '—'
  const date = new Date(iso.length === 10 ? iso + 'T00:00:00' : iso)
  if (Number.isNaN(date.getTime())) return iso
  return date.toLocaleDateString(lang === 'ar' ? 'ar-SA-u-ca-gregory-nu-latn' : 'en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  })
}

export const LANG_KEY = 'clicksy_lang'

export function readStoredLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY)
    if (stored === 'ar' || stored === 'en') return stored
  } catch {
    /* Storage can be blocked; Arabic is the project default. */
  }
  return 'ar'
}

export function fill(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(values[key] ?? ''),
  )
}

export function packageCopy(t: Messages, id: string) {
  const copy = (
    t.packageCopy as Record<string, { tagline: string; features: string[] }>
  )[id]
  return copy
}

export function eventCopy(t: Messages, id: string) {
  return (t.events as Record<string, { name: string; description: string }>)[id]
}

export function bookingEventTitle(
  t: Messages,
  eventTypeId: string,
  customEventName: string | undefined,
  fallback: string,
) {
  if (eventTypeId === 'other') return customEventName?.trim() || fallback
  return eventCopy(t, eventTypeId)?.name ?? fallback
}

export function statusLabel(t: Messages, status: string) {
  return (t.status as Record<string, string>)[status] ?? status
}

export function roleLabel(t: Messages, role: string) {
  return (t.roles as Record<string, string>)[role] ?? role
}
